// Writes the synthetic demo files to data/recon-sample/. Run: npm run sample
import { writeFileSync, mkdirSync } from "node:fs";
import { generateSample } from "../assets/js/recon/sample.js";

const { a, b, expected, counts } = generateSample(60);
const csv = rows => {
  const cols = Object.keys(rows[0]);
  const esc = v => /[",\n]/.test(String(v)) ? `"${String(v).replace(/"/g, '""')}"` : String(v);
  return [cols.join(","), ...rows.map(r => cols.map(c => esc(r[c])).join(","))].join("\n") + "\n";
};
mkdirSync("data/recon-sample", { recursive: true });
writeFileSync("data/recon-sample/side_a_invoices.csv", csv(a));
writeFileSync("data/recon-sample/side_b_bank_payments.csv", csv(b));
writeFileSync("data/recon-sample/expected_matches.json", JSON.stringify({ counts, expected }, null, 2));
writeFileSync("data/recon-sample/README.md", `# Synthetic reconciliation sample

Every row in these files is invented. Customer names, invoice numbers,
amounts and dates are generated by \`assets/js/recon/sample.js\` with a fixed
seed. No real company's data is used.

- \`side_a_invoices.csv\` — ${a.length} invoices (receivables)
- \`side_b_bank_payments.csv\` — ${b.length} bank receipts
- \`expected_matches.json\` — what the engine should find, by rule

Built-in mismatches: payments without a reference, amounts a few cents short,
typos in references, partial payments, one payment settling three invoices,
a duplicate payment, unpaid invoices across the ageing buckets, and stray
payments with no invoice.
`);
console.log(`wrote ${a.length} invoices and ${b.length} payments`);
