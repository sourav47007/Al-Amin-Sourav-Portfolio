// sync-meta.mjs — rewrites the <title> and social-preview tags of every page
// from content/site.js, so the name and URL live in one place.
// Run: npm run sync
import { readFileSync, writeFileSync } from "node:fs";
import { site } from "../content/site.js";

const base = site.url.replace(/\/$/, "");
const esc = s => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const projDesc = slug => site.projects.find(p => p.slug === slug)?.line || "";

// Page-level copy (UI text, not personal prose). Edit freely.
const PAGES = [
  { file: "index.html", path: "/", title: site.name, type: "website", image: "home",
    description: `${site.role}. Four finance tools you can use: ${site.projects.map(p => p.title).join(", ")}.` },
  { file: "about.html", path: "/about", title: `About · ${site.name}`, type: "profile", image: "home",
    description: "Bio, experience, education, competitions and leadership." },
  { file: "notes.html", path: "/notes", title: `Notes · ${site.name}`, type: "website", image: "home",
    description: "Short write-ups on finance, tools and things learned along the way." },
  { file: "valuation/index.html", path: "/valuation", title: "What's Priced In? · reverse DCF", type: "website", image: "valuation",
    description: `${projDesc("valuation")} See what revenue growth the share price assumes, with a sensitivity heatmap across growth and WACC.` },
  { file: "market/index.html", path: "/market", title: "Make Me a Market · pixel market-making game", type: "website", image: "market",
    description: `${projDesc("market")} Quote a bid and an ask, trade against bots, and learn spread capture, adverse selection and inventory risk.` },
  { file: "recon/index.html", path: "/recon", title: "Recon · in-browser reconciliation", type: "website", image: "recon",
    description: `${projDesc("recon")} Exact, tolerance, fuzzy and one-to-many matching, ageing and exports.` },
  { file: "truecost/index.html", path: "/truecost", title: "True Cost · credit offer decoder", type: "website", image: "truecost",
    description: `${projDesc("truecost")} Turns any offer into cash flows and a real annual rate. Compare up to three offers.` }
];

for (const p of PAGES) {
  const html = readFileSync(p.file, "utf8");
  const block = `<!-- meta:start (generated by \`npm run sync\` from content/site.js; edit there) -->
<title>${esc(p.title)}</title>
<meta name="description" content="${esc(p.description)}">
<meta property="og:type" content="${p.type}">
<meta property="og:title" content="${esc(p.title)}">
<meta property="og:description" content="${esc(p.description)}">
<meta property="og:url" content="${base}${p.path}">
<meta property="og:image" content="${base}/og/${p.image}.png">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="627">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${esc(p.title)}">
<meta name="twitter:description" content="${esc(p.description)}">
<meta name="twitter:image" content="${base}/og/${p.image}.png">
<!-- meta:end -->`;
  const out = html.replace(/<!-- meta:start[\s\S]*?<!-- meta:end -->/, block);
  if (out === html) console.log(`unchanged ${p.file}`); else { writeFileSync(p.file, out); console.log(`updated ${p.file}`); }
}
